"""Copied native Data pages for political/national/diplomatic read models.

This is V3 business composition, not a game rule evaluator. Original expressions
run inside data.project_page. No command is generated by a read, no pointer or
provider row is retagged, and a source_index is an observation, never a game ID.
The caller's ordinary query executor owns pending work and copied allocations.
"""
from __future__ import annotations

from dataclasses import dataclass

from .. import v3_data as data, v3_player_control as player
from ._text import display_field
from ._values import fixed_decimal
from ._projection import _projection_page, _projection_value


@dataclass(frozen=True)
class Field:
    name: str
    expression: str | data.NativeField
    kind: int | None = None
    text: bool = False
    full_id: bool = False


def _id(value, label="country_id"):
    if type(value) is not int or not 0 <= value < 0xffffffff:
        raise ValueError(label + " must be a complete uint32 ID; zero is valid")
    return value


async def resolve_country_id(ctx, selected=None):
    """Resolve only an actual selection, never separately probe its identity."""
    if selected is None:
        return await ctx.country_id()
    if isinstance(selected, dict):
        selected = selected.get("id", selected.get("country_id"))
    if isinstance(selected, str):
        tag = selected.strip().upper()
        if len(tag) != 3 or not tag.isascii() or not tag.isalnum():
            raise ValueError("country must be a full native ID or three-character tag")
        result = await ctx.query("politics.country_tag", lambda: player.resolve_tag(
            ctx.native, tag, adapter=ctx.adapters["console"], process=ctx.process))
        if result.error or result.target_error:
            from ._core import NativeRejection
            raise NativeRejection("country tag resolution", result)
        return result.target_country_id
    return _id(selected)


async def binding(ctx, domain, full_id):
    """Use existing type metadata; no extra world-status call for a cached type."""
    types = getattr(ctx, "_types", {})
    type_id = types.get(domain)
    if type_id is None:
        type_id = await ctx.type_id(domain)
    return data.ObjectBinding.full_id(domain, type_id, _id(full_id, domain + " ID"))


def _field_value(field, cell):
    value, copied_reason = _projection_value(cell)
    reasons = [copied_reason] if copied_reason else []
    if cell is None:
        return value, copied_reason
    if cell.binding_error:
        reasons.append("native provider binding error " + str(cell.binding_error))
    if field.kind is not None and cell.kind != field.kind:
        reasons.append("native kind " + str(cell.kind) + " differs from expected " + str(field.kind))
    if isinstance(value, data.FixedPoint):
        value = fixed_decimal(value)
    if field.full_id:
        if type(value) is int and cell.kind in (data.Kind.I32, data.Kind.U32):
            value &= 0xffffffff
            if value == 0xffffffff:
                reasons.append("native invalid-reference sentinel")
        elif value is not None:
            reasons.append("native identity is not an int32/uint32 full reference")
    return value, "; ".join(reasons) or None


async def _page(ctx, label, fields, binding_rows, *, source_expression=None,
                start=0, steps=(), source_arguments=()):
    # The shared V3 projection seam owns query continuation, partial copies and
    # cleanup warnings. Business models only select native fields and units.
    return await _projection_page(ctx, label, (f.expression for f in fields), binding_rows,
        source_expression=source_expression, start=start, limit=64,
        steps=steps, source_arguments=source_arguments)


async def project(api, label, fields, binding_rows, *, source_expression=None,
                  steps=(), source_arguments=(), perform=True, owner=None):
    """Read a bounded page sequence, keeping per-field errors and all copied rows.

    The source is evaluated once per page. Fields compile once per page, not once
    per row. Page counts can change between calls; no atomic cross-page snapshot
    is claimed. More than32fields needs a separate explicit read, not a hidden
    index-based merge of independently changing providers.
    """
    ctx = api._ctx if owner is None else owner
    fields = tuple(fields)
    if not fields or len(fields) > 32 or not all(isinstance(f, Field) for f in fields):
        raise ValueError("choose1..32Field objects")
    if len({f.name for f in fields}) != len(fields):
        raise ValueError("projection field names must be unique")
    binding_rows = tuple(tuple(row) for row in binding_rows)
    steps, source_arguments = tuple(steps), tuple(source_arguments)
    async def read():
        rows, pages, errors = [], [], []
        start = 0
        while True:
            page = await _page(ctx, label, fields, binding_rows,
                source_expression=source_expression, start=start, steps=steps,
                source_arguments=source_arguments)
            pages.append(page)
            if page.error:
                errors.append({"page_start": start, "native_error": page.error})
            if not page.count_valid:
                errors.append({"page_start": start, "reason": "native source count unavailable"})
            if page.fields_count != len(fields):
                errors.append({"page_start": start, "reason": "native field count differs from requested fields"})
            for offset, cells in enumerate(page.rows):
                by_field = {cell.field: cell for cell in cells}
                row = {"source_index": page.start + offset, "reasons": {}}
                for index, field in enumerate(fields):
                    value, reason = _field_value(field, by_field.get(index))
                    if field.text:
                        row.update(display_field(value, field.name))
                    else:
                        row[field.name] = value
                    if reason:
                        row["reasons"][field.name] = reason
                rows.append(row)
            if not source_expression or not page.has_more:
                break
            if page.next <= start:
                errors.append({"page_start": start, "reason": "native source page did not advance"})
                break
            start = page.next
        complete = not errors and all(not row["reasons"] for row in rows)
        result = {"rows": rows, "status": "observed" if complete else "partial" if rows else "unavailable",
                  "complete": complete, "source_count": pages[-1].source_count if pages and pages[-1].count_valid else None,
                  "source_expression": source_expression, "reasons": errors, "native_pages": pages,
                  "atomic_snapshot": False, "source_index_semantics": "occurrence only; not a stable native ID"}
        return result
    return await api._ctx.perform(label, read) if perform else await read()


async def country_source(api, label, source_expression, fields, *, country_id=None,
                         steps=(), source_arguments=(), perform=True):
    async def read():
        selected = await resolve_country_id(api._ctx, country_id)
        root = await binding(api._ctx, "Country", selected)
        result = await project(api, label, fields, ((root,),), source_expression=source_expression,
            steps=steps, source_arguments=source_arguments, perform=False)
        result["country_id"] = selected
        return result
    return await api._ctx.perform(label, read) if perform else await read()


async def snapshot(api, label, fields, binding_rows, *, perform=True, owner=None):
    """One copied row flattened for a scalar read model, retaining page errors."""
    fields = tuple(fields)
    async def read():
        result = await project(api, label, fields, binding_rows, perform=False, owner=owner)
        flat = {key: value for key, value in result.items() if key != "rows"}
        if result["rows"]:
            observed = result["rows"][0]
            flat.update({key: value for key, value in observed.items() if key not in ("source_index", "reasons")})
            flat["reasons"] = {"fields": observed["reasons"], "pages": result["reasons"]}
        else:
            for field in fields:
                flat[field.name] = None
            flat["reasons"] = {"fields": {field.name: "native page returned no row" for field in fields},
                               "pages": result["reasons"]}
            flat["complete"] = False
            flat["status"] = "unavailable"
        return flat
    return await api._ctx.perform(label, read) if perform else await read()


async def country_snapshot(api, label, fields, *, country_id=None, perform=True):
    async def read():
        selected = await resolve_country_id(api._ctx, country_id)
        root = await binding(api._ctx, "Country", selected)
        result = await snapshot(api, label, fields, ((root,),), perform=False)
        result["country_id"] = selected
        return result
    return await api._ctx.perform(label, read) if perform else await read()


async def state_snapshot(api, label, fields, *, state_id, country_id=None, perform=True):
    async def read():
        selected = await resolve_country_id(api._ctx, country_id)
        country = await binding(api._ctx, "Country", selected)
        state = await binding(api._ctx, "State", state_id)
        result = await snapshot(api, label, fields, ((country, state),), perform=False)
        result.update(country_id=selected, state_id=state_id)
        return result
    return await api._ctx.perform(label, read) if perform else await read()
